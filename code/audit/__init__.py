r"""Аудит существующих наборов вопросов: почему чужие эталоны не подходят для долговечной оценки.

Базовый вычислительный эксперимент работы (ADR-020). Измеряется, как быстро устаревают
эталонные ответы существующих наборов: для вопроса $q$ из версии набора $v_0$ и более поздней
версии $v$ вычисляется индикатор $s(q; v) = \mathbb{I}[A^*_v(q) \ne A^*_{v_0}(q)]$, а по типу
вопроса $c$ — доля устаревших эталонов $\bar s_c(\Delta t)$ с перцентильным бутстреп-интервалом.
Для остальных наборов измеряются доли вопросов с дефектами, мешающими долговечной оценке:
привязка к моменту запроса, правки эталона, нестабильные идентификаторы.

Расчёты и рисунки разделены: модули ``compute_*`` читают сырые данные и пишут только таблицы
в ``results/audit/``, модуль ``plots`` читает эти таблицы и строит рисунки в ``results/figures/``.

Модули:

* ``download`` — загрузка сторонних наборов в кэш ``data/external/`` (версии зафиксированы
  коммитами репозиториев и тегами Hugging Face);
* ``compute_freshqa`` — устаревание эталонов FreshQA (Vu et al., 2023) по 75 версиям;
* ``compute_datasets`` — дефекты RGB, CDQA, ChronoQA и DRAGOn;
* ``compute_seed_pool`` — эвристическая проверка 388 вопросов промышленной системы правилами
  $E_1$, $E_2$, $E_4$;
* ``compute_summary`` — сводная таблица наборов «почему не подходят»;
* ``plots`` — эскиз графика ошибок и рисунок с главным выводом;
* ``markers`` — словари маркеров времени и правил исключения для русского, английского и китайского.

Запуск всего эксперимента из корня репозитория: ``python -m code.audit`` (или ``make audit``).
Сырые данные сторонних наборов не входят в репозиторий; в ``results/audit/`` сохраняются только
производные таблицы и ``sources.csv`` с адресами и sha256 использованных файлов.
"""


r"""Словари маркеров для эвристической проверки формулировок вопросов.

Маркеры приближают правила исключения $E_1$–$E_5$ (приложение статьи) по тексту вопроса:

* ``RELATIVE_TIME`` — слова, привязывающие ответ к моменту запроса («сейчас», «последний»,
  «в этом году»; «最近», «目前», «今年»; «current», «latest»), то есть правило $E_2$;
* ``DATE_ANCHOR`` — явная дата-якорь в тексте вопроса (год, день и месяц);
* ``SEED_POOL_RULES`` — правила $E_1$ (прогнозы и гипотетика), $E_2$ и $E_4$ (оценочная позиция)
  для русских формулировок, а также фрагменты латиницей или иероглифами и составные вопросы.

Это эвристика, а не разметка: маркер может сработать на допустимом вопросе («последний раунд
переговоров 2023 года») и пропустить недопустимый. Поэтому вместе с долями публикуются сами
отмеченные вопросы, по которым точность правил проверяется вручную.
"""

from __future__ import annotations

import re

_RU_MONTHS = "января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря"
_EN_MONTHS = "january|february|march|april|may|june|july|august|september|october|november|december"

RELATIVE_TIME: dict[str, re.Pattern] = {
    "ru": re.compile(
        r"\b(сейчас|ныне|нынешн\w*|в настоящее время|на данный момент|на сегодня\w*|сегодня\w*"
        r"|текущ\w*|последн\w*|новейш\w*|недавн\w*|в этом году|в прошлом году|в следующем году"
        r"|в этом месяце|на этой неделе|действующ\w*)\b",
        re.IGNORECASE,
    ),
    "en": re.compile(
        r"\b(current(ly)?|latest|most recent|recent(ly)?|now|nowadays|today|so far|to date|upcoming"
        r"|(this|last|next) (year|month|week|season))\b",
        re.IGNORECASE,
    ),
    "zh": re.compile(
        r"(最近|最新|目前|现在|当前|如今|近期|近日|日前|前不久|近年|至今|今年|本年|去年|明年"
        r"|上个月|本月|这个月|下个月|本周|上周|下周|昨天|今天|明天)"
    ),
}

DATE_ANCHOR: dict[str, re.Pattern] = {
    "ru": re.compile(rf"\b(19|20)\d\d\b|\b\d{{1,2}}\s+({_RU_MONTHS})\b", re.IGNORECASE),
    "en": re.compile(rf"\b(19|20)\d\d\b|\b({_EN_MONTHS})\s+\d{{1,2}}\b", re.IGNORECASE),
    "zh": re.compile(r"(19|20)\d\d|\d{1,2}月\d{1,2}日"),
}

SEED_POOL_RULES: dict[str, tuple[str, re.Pattern]] = {
    "E1": (
        "прогноз или гипотетика: будет, может, повлияет, последствия, перспективы, ожидается, планирует, если",
        re.compile(
            r"\b(будет|будут|станет|станут|может|могут|смож\w*|повлия\w*|последстви\w*|перспектив\w*"
            r"|прогноз\w*|ожида\w*|планиру\w*|намерен\w*|в будущем|если)\b",
            re.IGNORECASE,
        ),
    ),
    "E2": (
        "привязка к моменту запроса: сейчас, текущий, последний, недавно, в этом году",
        RELATIVE_TIME["ru"],
    ),
    "E4": (
        "оценочная позиция: оценивает, мнение, считает, позиция, реакция, эффективность",
        re.compile(
            r"\b(оценива\w*|оценк\w*|мнени\w*|счита\w*|позици\w*|реакци\w*|восприн\w*|воспринима\w*"
            r"|критик\w*|опасени\w*|эффективн\w*|успешн\w*)\b",
            re.IGNORECASE,
        ),
    ),
    "foreign_script": (
        "фрагмент латиницей или иероглифами в русском вопросе; часть из них — допустимые названия",
        re.compile(r"\b[A-Za-z]*[a-z][A-Za-z]{2,}\b|[一-鿿]"),
    ),
    "compound": (
        "составной вопрос: второй вопрос после запятой и союза «и»",
        re.compile(
            r",\s*(и|а также)\s+(как|какие|какой|какая|каков\w*|почему|что|кто|где|когда|сколько"
            r"|насколько|чем|в чём|в чем)\b",
            re.IGNORECASE,
        ),
    ),
}

# Правила, приближающие запрет на нестатичные вопросы ($E_1$, $E_2$, $E_4$).
STATIC_RULES = ("E1", "E2", "E4")


def has(pattern: re.Pattern, text: str) -> bool:
    return pattern.search(str(text)) is not None
